"""Convert Truth-DB snapshots (truth_db_project/data/python/<lib>/<ver>.json) into the
backend's snapshot format (backend/data/<lib>/<ver>.json).

    cd backend
    python scripts/import_truth_db.py                 # all libraries / versions
    python scripts/import_truth_db.py requests 2.31.0 # one snapshot

Conservative rules (never claim more certainty than the Truth DB has):
  * **kwargs in the real signature      -> parameterCompleteness = "partial"
  * *args in the real signature          -> signatureCompleteness = "partial", no positional limit
  * exceptions                           -> signature "partial" (subclasses inherit BaseException.__init__)
  * attributes / constants / modules     -> no parameter data ("unknown")
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "truth_db_project" / "data" / "python"
DST = ROOT / "backend" / "data"
CALLABLE = {"function", "method", "class", "exception"}


def convert_symbol(e: dict) -> dict:
    kind = e.get("kind", "function")
    out = {"kind": kind, "module": e.get("module", ""), "description": ""}
    if kind not in CALLABLE:
        return out
    accepted = sorted(e.get("accepted_arguments", e.get("arguments", [])))
    positional = list(e.get("arguments", []))
    var_kw, var_args = bool(e.get("accepts_var_kwargs")), bool(e.get("accepts_var_args"))
    out["parameters"] = accepted
    out["parameterCompleteness"] = "partial" if var_kw else "verified"
    out["positionalParameters"] = positional
    if var_args or kind == "exception":
        out["signatureCompleteness"] = "partial"
    else:
        out["signatureCompleteness"] = "verified"
        out["minPositionalArguments"] = len(e.get("required", []))
        out["maxPositionalArguments"] = len(positional)
    return out


def convert(lib: str, version: str) -> Path:
    raw = json.loads((SRC / lib / f"{version}.json").read_text(encoding="utf-8"))
    snap = {
        "library": raw["library"],
        "version": raw["version"],
        "source": {"name": f"{lib} {version} (introspected with inspect.signature by truth_db_project)",
                   "url": f"https://pypi.org/project/{lib}/{version}/"},
        "snapshotCompleteness": "complete",
        "notes": "Generated by scripts/import_truth_db.py from the Truth DB. Do not edit by hand.",
        "symbols": {k: convert_symbol(v) for k, v in sorted(raw["apis"].items())},
    }
    out = DST / lib / f"{version}.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(snap, indent=1) + "\n", encoding="utf-8")
    return out


def main(argv: list[str]) -> int:
    if len(argv) == 2:
        pairs = [(argv[0], argv[1])]
    else:
        pairs = [(d.parent.name, d.stem) for d in sorted(SRC.glob("*/*.json"))]
    for lib, ver in pairs:
        print("wrote", convert(lib, ver).relative_to(ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
